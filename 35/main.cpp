class Solution
{
  public:
    int binary_search(vector<int> &nums, int target)
    {
        int left  = 0;
        int right = nums.size() - 1;

        while (left <= right)
        {
            int mid = left + (right - left) / 2;
            if (nums[mid] == target)
            {
                return mid;
            }
            else if (nums[mid] > target)
            {
                right = mid - 1;
            }
            else
            {
                left = mid + 1;
            }
        }
        return left;
    }

    int searchInsert(vector<int> &nums, int target)
    {
        return binary_search(nums, target);
    }
};

